// One signature sound for every item (all 24 ids in config.js ITEMS), plus a hit sound for items that strike somebody, an end cue for timed
// items, and the item-slot sounds (roulette landing, swap, slots full). Everything is synthesised with the toolkit in synth.js: no samples.
//
// Naming (see ItemManager / AudioManager): `item-use-<id>` when the item is used, `item-hit-<id>` when it hits (or is applied to) a racer,
// `item-end-<id>` when a timed effect or shield ends. The recipes below are written at "natural" levels; each is then trimmed by
// `ITEM_LEVELS[name]` (sfx_levels.js, generated by `node tools/sfx_audition.mjs --calibrate`) so every one lands at the same loudness and peaks below -3 dBFS.
// Each sound is meant to be told apart with eyes closed: different pitch range, timbre and rhythm. Lengths are 0.15 to 1.2 s.
import { mtof, tone, burst, kick, drum, bell, noteToMidi } from './synth.js';
import { ITEM_LEVELS } from './sfx_levels.js';

const note = (n) => mtof(noteToMidi(n));
/** deterministic pseudo-random in 0..1 for step i (no Math.random: renders are reproducible) */
const rnd = (i, seed = 1) => { const x = Math.sin(i * 12.9898 + seed * 78.233) * 43758.5453; return x - Math.floor(x); };
/** rising / falling noise sweep */
const sweep = (c, out, t, { len = 0.3, f0 = 400, f1 = 3000, vol = 0.3, q = 1.2, a = 0.01, kind = 'white', type = 'bandpass' } = {}) =>
  burst(c, out, t, { dur: len, vol, type, freq: f0, freqEnd: f1, q, a, d: len * 0.4, s: 0.3, r: len * 0.45, kind });
/** a soft noise swell that builds then stops */
const swell = (c, out, t, { len = 0.4, f = 2000, f1 = 0, vol = 0.2, q = 1, type = 'bandpass', kind = 'white' } = {}) =>
  burst(c, out, t, { dur: len, vol, type, freq: f, freqEnd: f1, q, a: len * 0.7, d: len * 0.2, s: 0.4, r: len * 0.3, kind });
const click = (c, out, t, { vol = 0.3, f = 1700 } = {}) => {
  burst(c, out, t, { dur: 0.015, vol: vol * 0.6, type: 'highpass', freq: 2500, a: 0.0006 });
  tone(c, out, t, { wave: 'square', freq: f, dur: 0.008, a: 0.0005, d: 0.02, s: 0, r: 0.02, vol: vol * 0.5, cutoff: 3500 });
};

/** @type {Record<string, {dur: number, gap?: number, play: (c: BaseAudioContext, out: AudioNode, t: number, o: {pitch: number, vol: number}) => void}>} */
export const ITEM_RECIPES = {};
const r = (name, dur, play, gap = 0.08) => { ITEM_RECIPES[name] = { dur, gap, play }; };

