/** Sounds defined in sfx.js (Biscuit's items) that get the same loudness trim. */
export const BISCUIT_ITEM_SFX = ['item-use-woof', 'item-hit-woof', 'item-use-poo', 'item-hit-poo', 'item-use-zoomies', 'item-use-fetch', 'item-hit-fetch', 'item-catch'];

/** Every sound that takes a loudness trim from sfx_levels.js. */
export const levelledNames = () => [...Object.keys(ITEM_RECIPES), ...BISCUIT_ITEM_SFX];

const clipCurves = new WeakMap();
/** A fixed soft clipper: y = 0.7 tanh(x / 0.7). Unity gain for small signals, never above 0.7, identical in every browser (unlike a compressor's makeup gain). */
function softClip(c) {
  let curve = clipCurves.get(c);
  if (!curve) {
    curve = new Float32Array(2049);
    for (let i = 0; i < curve.length; i++) { const x = (i / 1024 - 1) * 2; curve[i] = 0.7 * Math.tanh(x / 0.7); }   // input range -2..2
    clipCurves.set(c, curve);
  }
  const sh = c.createWaveShaper(); sh.curve = curve;
  return sh;
}

/** Wrap a play function: scaled by the calibrated trim (and the caller's vol), then soft-clipped so nothing can pass 0.7 (about -3 dBFS). */
export const withTrim = (name, play) => (c, out, t, o) => {
  const g = c.createGain(); g.gain.value = (ITEM_LEVELS[name] ?? 1) * o.vol;
  const sh = softClip(c);
  g.connect(sh); sh.connect(out);
  play(c, g, t, { pitch: o.pitch, vol: 1 });
};

/** Register every recipe in the SFX table (`def` is sfx.js's definer) and trim the Biscuit sounds already there. */
export function installItemSfx(SFX, def) {
  for (const [name, rc] of Object.entries(ITEM_RECIPES)) {
    def(name, rc.dur, withTrim(name, rc.play), { gap: rc.gap });
    SFX[name].raw = rc.play;
  }
  for (const name of BISCUIT_ITEM_SFX) {
    const d = SFX[name];
    if (!d) continue;
    d.raw = d.play;
    d.play = withTrim(name, d.raw);
  }
}
